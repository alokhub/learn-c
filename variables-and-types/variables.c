#include <stdio.h>

int main() {
    // program in c to declare variables of different types and print their values

    // declare variables of different types
    int a = 10;
    float b = 20.5;
    char c = 'A';
    double d = 30.123456;

    // print the values of the variables
    printf("Integer: %d\n", a);
    printf("Float: %.2f\n", b);
    printf("Character: %c\n", c);
    printf("Double: %.6lf\n", d);
    return 0;
}